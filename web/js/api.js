/* api.js — classic script build (see web/tools/to-classic.mjs).
   Loaded in order from index.html so the site also works from file://,
   where browsers block ES modules and fetch(). Source of truth is this file. */
(function (SR) {
'use strict';
  // dependencies pulled from the shared namespace
  const { lookup, normalizeData, buildQuery, datasetFromRows } = SR;

/**
 * api.js — where the rows come from.
 *
 * Order of preference (mirrors the blueprint's "static fallback" rule):
 *   1. GET /api/lookup?...        → the real service (soil: api/lookup.py)
 *   2. data/combos.json           → static export, matched in-browser by lookup.js
 *   3. web/fixtures/sample-combos.json → demo data, clearly labelled as such
 *
 * Every path returns the same CONTRACT §4 response shape, plus a `source` field
 * in `dataset` describing which one answered, so the UI can be honest in the
 * footer ("served by the live API" vs "sample data").
 *
 * Nothing here throws in a way the UI can't render: failures degrade to the next
 * source and, if all fail, the caller gets a structured error it can show.
 */


const FIXTURE_URL = 'fixtures/sample-combos.json';
const STATIC_URL_CANDIDATES = ['../data/combos.json', 'data/combos.json'];

/** /api/lookup with query params. */
async function fetchApiLookup(q, { signal, timeoutMs = 4000 } = {}) {
  const qs = new URLSearchParams();
  for (const k of ['hw', 'model', 'runtime', 'status', 'kind', 'q', 'limit']) {
    if (q[k] !== null && q[k] !== undefined && q[k] !== '') qs.set(k, String(q[k]));
  }
  const url = `api/lookup${qs.toString() ? `?${qs}` : ''}`;
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), timeoutMs);
  if (signal) signal.addEventListener('abort', () => ctrl.abort(), { once: true });
  try {
    const res = await fetch(url, { headers: { accept: 'application/json' }, signal: ctrl.signal });
    const ct = res.headers.get('content-type') || '';
    if (!res.ok) throw new Error(`api/lookup → HTTP ${res.status}`);
    if (!ct.includes('json')) throw new Error('api/lookup → not JSON (static host?)');
    const json = await res.json();
    if (!json || !Array.isArray(json.rows)) throw new Error('api/lookup → malformed response');
    return { ...json, dataset: { ...(json.dataset || {}), source: 'api' } };
  } finally {
    clearTimeout(timer);
  }
}

let staticCache = null; // {rows, dataset, source}

/** Load data/combos.json (or JSONL) once. Throws if no candidate loads. */
async function loadStatic({ signal, force = false } = {}) {
  if (staticCache && !force) return staticCache;
  const errors = [];
  for (const url of STATIC_URL_CANDIDATES) {
    try {
      // no-store: combos.json is regenerated by the pipeline; a stale cached copy
      // would make the site claim a stale as_of, which is the failure mode this
      // whole product exists to avoid.
      const res = await fetch(url, { cache: 'no-store', signal });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const text = await res.text();
      if (!text.trim()) throw new Error('empty body');
      const parsed = text.trim().startsWith('{') || text.trim().startsWith('[') ? safeJson(text) : null;
      const { rows, dataset } = normalizeData(parsed !== null ? parsed : text);
      staticCache = {
        rows,
        dataset: { ...datasetFromRows(rows), ...dataset, source: 'static', source_url: url },
        source: 'static'
      };
      return staticCache;
    } catch (err) {
      errors.push(`${url}: ${err.message}`);
    }
  }
  const e = new Error(`static dataset unavailable — ${errors.join('; ')}`);
  e.cause = errors;
  throw e;
}

function safeJson(text) {
  try {
    return JSON.parse(text);
  } catch {
    return null;
  }
}

/** Demo data. Kept loadable even when the server answers, so it can be forced. */
async function loadFixture({ signal } = {}) {
  const res = await fetch(FIXTURE_URL, { cache: 'no-store', signal });
  if (!res.ok) throw new Error(`fixture → HTTP ${res.status}`);
  const { rows, dataset } = normalizeData(await res.json());
  return {
    rows,
    dataset: {
      ...datasetFromRows(rows),
      ...dataset,
      source: 'fixture',
      source_url: FIXTURE_URL
    },
    source: 'fixture'
  };
}

/**
 * One call, all sources. Returns the CONTRACT response and records which source
 * answered in `dataset.source`.
 *
 * Fallback chain (each step is only skipped when it is known not to exist):
 *   /api/lookup → data/combos.json → web/fixtures/sample-combos.json
 * The fixture step is what keeps the site demoable before the pipeline has
 * produced an export; `dataset.source === 'fixture'` is what makes the UI say so.
 *
 * @param {object} query  {hw, model, runtime, status, kind, q, limit}
 * @param {{signal, prefer?: 'fixture'|'static'|'auto'}} opts
 */
async function getLookup(query, opts = {}) {
  const q = buildQuery(query);
  const prefer = opts.prefer || 'auto';

  if (prefer === 'auto' && !isFileProtocol()) {
    try {
      const res = await fetchApiLookup(q, opts);
      return { ...res, dataset: { ...res.dataset, source: 'api' } };
    } catch (err) {
      if (typeof console !== 'undefined' && !(opts.signal && opts.signal.aborted)) {
        console.info('[combo-index] api unavailable, falling back to static export:', err.message);
      }
    }
  }

  const data = await loadRowsWithFixtureFallback(prefer, opts);
  const res = lookup(data.rows, q, data.dataset, { datasetSource: data.source });
  res.dataset = { ...res.dataset, source: data.source, source_url: data.dataset.source_url };
  res.all_rows = data.rows;
  return res;
}

/** The row set for browse mode, same source order as getLookup. */
async function getAllRows(opts = {}) {
  const prefer = opts.prefer || 'auto';
  if (prefer === 'auto' && !isFileProtocol()) {
    try {
      const res = await fetchApiLookup({ limit: 500 }, opts);
      const { rows } = normalizeData(res);
      return {
        rows,
        dataset: { ...datasetFromRows(rows), ...res.dataset, source: 'api' },
        source: 'api'
      };
    } catch (err) {
      if (typeof console !== 'undefined') {
        console.info('[combo-index] api unavailable, falling back to static export:', err.message);
      }
    }
  }
  return loadRowsWithFixtureFallback(prefer, opts);
}

/**
 * static (or fixture when asked) with a fixture fallback, so a missing
 * combos.json never leaves the page blank. If BOTH fail, the static error is
 * rethrown — it is the more informative one ("combos.json missing" beats
 * "fixture missing" when the fixture is the thing that should always exist).
 */
/** On file:// there is no server to ask: go straight to the snapshot. */
function isFileProtocol() {
  try {
    return typeof location !== 'undefined' && location.protocol === 'file:';
  } catch {
    return false;
  }
}

async function loadRowsWithFixtureFallback(prefer, opts) {
  if (isFileProtocol() && prefer !== 'static') {
    const snap = loadSnapshot();
    if (snap) return snap;
  }
  try {
    if (prefer === 'fixture') return await loadFixture(opts);
    return await loadStatic(opts);
  } catch (staticErr) {
    if (prefer === 'fixture') {
      const snap = loadSnapshot();
      if (snap) return snap;
    }
    // file:// : fetch() cannot read local files at all. Fall back to the
    // generated snapshot (a classic script that was already executed), then the
    // hand-written fixture — which on file:// is also fetch-blocked, so the
    // snapshot is the one that actually works there.
    const snap = loadSnapshot();
    if (snap) return snap;
    try {
      const fx = await loadFixture(opts);
      fx.dataset = { ...fx.dataset, fallback_reason: staticErr.message };
      return fx;
    } catch {
      throw staticErr;
    }
  }
}

/**
 * The inlined dataset (web/snapshot.js, generated by tools/inline-snapshot.mjs).
 * Exists because file:// pages cannot fetch local JSON. Over http it is never
 * reached: /api/lookup and data/combos.json answer first.
 */
function loadSnapshot() {
  const raw = typeof window !== 'undefined' ? window.SOLVE_RUN_SNAPSHOT : null;
  if (!raw || !Array.isArray(raw.rows) || !raw.rows.length) return null;
  const { rows, dataset } = normalizeData(raw);
  return {
    rows,
    dataset: {
      ...datasetFromRows(rows),
      ...dataset,
      source: 'snapshot',
      source_url: 'snapshot.js'
    },
    source: 'snapshot'
  };
}

function clearStaticCache() {
  staticCache = null;
}

/**
 * POST a want-vote. CONTRACT leaves the write path to the API owner; we try the
 * conventional endpoint and report honestly if it isn't there yet, so the button
 * never pretends a vote was counted.
 */
/**
 * POST a want-vote. The API is `POST /api/want/{id}` with `{"voter": "<key>"}`
 * (idempotent per voter). The `{extra}` spread exists so callers can pass a
 * stable device key; without it the API derives one per IP+UA.
 *
 * Never throws for network/HTTP reasons: the caller needs to be able to say
 * honestly whether the vote was recorded, rather than crashing the page.
 */
async function voteFor(id, { signal, extra = {} } = {}) {
  try {
    const res = await fetch(`api/want/${encodeURIComponent(id)}`, {
      method: 'POST',
      headers: { 'content-type': 'application/json', accept: 'application/json' },
      body: JSON.stringify({ id, ...extra }),
      signal
    });
    const json = await res.json().catch(() => null);
    if (!res.ok) {
      const msg = (json && json.error && json.error.message) || `HTTP ${res.status}`;
      return { ok: false, error: msg, status: res.status, response: json };
    }
    return {
      ok: true,
      votes: json && (json.want_votes ?? json.votes ?? json.total),
      voted: json ? json.voted !== false : true,
      response: json
    };
  } catch (err) {
    if (err.name === 'AbortError') throw err;
    return { ok: false, error: err.message };
  }
}

/**
 * POST the miss report — the loop where "found nothing" is a contribution.
 * Body is `{"query": {...}, "searcher_key": "..."}` per api/server.py.
 */
async function reportMiss({ query, searcher_key }, { signal } = {}) {
  try {
    const res = await fetch('api/miss', {
      method: 'POST',
      headers: { 'content-type': 'application/json', accept: 'application/json' },
      body: JSON.stringify({ query, searcher_key }),
      signal
    });
    const json = await res.json().catch(() => null);
    if (!res.ok) {
      const msg = (json && json.error && json.error.message) || `HTTP ${res.status}`;
      return { ok: false, error: msg, status: res.status, response: json };
    }
    return { ok: true, response: json };
  } catch (err) {
    if (err.name === 'AbortError') throw err;
    return { ok: false, error: err.message };
  }
}

/**
 * data/taxonomy.json — used only to *construct* a demo miss (an arch with zero
 * rows) and to label vendor/arch pairs. Optional: every caller tolerates null.
 */
const TAXONOMY_URLS = ['api/taxonomy', '../data/taxonomy.json', 'data/taxonomy.json'];

async function loadTaxonomy({ signal } = {}) {
  for (const url of TAXONOMY_URLS) {
    try {
      const res = await fetch(url, { cache: 'no-store', signal });
      if (!res.ok) continue;
      const json = await res.json();
      // /api/taxonomy may wrap the file; accept either shape.
      const tax = json && json.hw_archs ? json : json && json.taxonomy && json.taxonomy.hw_archs ? json.taxonomy : null;
      if (tax) return tax;
    } catch {
      /* try next */
    }
  }
  return null;
}

  Object.assign(SR, { FIXTURE_URL, STATIC_URL_CANDIDATES, fetchApiLookup, loadStatic, loadFixture, getLookup, getAllRows, clearStaticCache, voteFor, reportMiss, TAXONOMY_URLS, loadTaxonomy });
})(window.__SR = window.__SR || {});
